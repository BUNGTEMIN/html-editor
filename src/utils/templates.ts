export function cloneTemplateToDocument(templateId: string): EmailDocument {
  const preset =
    TEMPLATE_PRESETS.find((t) => t.id === templateId) ?? TEMPLATE_PRESETS[0];
  const cloned = JSON.parse(JSON.stringify(preset.document)) as Omit<
    EmailDocument,
    'id' | 'updatedAt'
  >;

  return {
    id: generateId('doc'),
    updatedAt: new Date().toISOString(),
    title: cloned.title,
    pageStyle: cloned.pageStyle,
    blocks: cloned.blocks.map((block) => ({
      ...block,
      id: generateId(block.type),
    })),
  };
}
