export const TEMPLATE_CATEGORIES = [
  'Semua',
  ...Array.from(new Set(TEMPLATE_PRESETS.map((t) => t.category))),
];

export function filterTemplates(
  presets: TemplatePreset[],
  query: string,
  category: string
): TemplatePreset[] {
  const q = query.trim().toLowerCase();
  return presets.filter((preset) => {
    const matchesCategory =
      !category || category === 'Semua' || preset.category === category;
    if (!matchesCategory) return false;
    if (!q) return true;
    return (
      preset.name.toLowerCase().includes(q) ||
      preset.description.toLowerCase().includes(q) ||
      preset.category.toLowerCase().includes(q)
    );
  });
}

export function cloneTemplateToDocument(templateId: string): EmailDocument {
  const preset =
    TEMPLATE_PRESETS.find((t) => t.id === templateId) ?? TEMPLATE_PRESETS[0];
  const cloned = JSON.parse(JSON.stringify(preset.document)) as Omit<
    EmailDocument,
    'id' | 'updatedAt'
  >;

  return {
    id: generateId('doc'),
    updatedAt: new Date().toISOString(),
    title: cloned.title,
    pageStyle: cloned.pageStyle,
    blocks: cloned.blocks.map((block) => ({
      ...block,
      id: generateId(block.type),
    })),
  };
}
